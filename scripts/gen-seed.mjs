// Writes database/seed.sql from src/data/permissions.json (the Roles and permissions rows and their defaults).
// Run after changing permissions.json:  node scripts/gen-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const { rows } = JSON.parse(readFileSync(new URL('src/data/permissions.json', root), 'utf8'))
const { applied } = JSON.parse(readFileSync(new URL('src/data/siteDefaults.json', root), 'utf8'))
const appliedSets = { palette: 'lime-black', typography: 'typography-1', background: 'bg-dots', logos: 'logo-monogram', menu: 'menu-default', events: 'events-default', ...applied }
delete appliedSets.pages
const ROLES = ['visitor', 'member', 'arbiter', 'organiser']
const q = (s) => (s == null ? 'NULL' : `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`)

const perms = rows.map((r, i) => `  (${q(r.key)}, ${q(r.group)}, ${q(r.label)}, ${q((r.scopes ?? []).join(','))}, ${i + 1})`)
const cells = rows.flatMap((r) =>
  ROLES.map((role, i) => {
    const v = r.d[i]
    return `  (${q(role)}, ${q(r.key)}, ${v ? 1 : 0}, ${typeof v === 'string' ? q(v) : r.scopes ? q(r.scopes[0]) : 'NULL'})`
  }),
)

const sql = `-- Principles: starting records. Run after schema.sql (phpMyAdmin › SQL, or: mysql -h HOST -u USER -p DB < seed.sql).
-- Generated by scripts/gen-seed.mjs from src/data/permissions.json – edit that file, not this one.
-- Safe to re-run: permission labels are refreshed, but role choices made in
-- User management › Roles and permissions are kept (INSERT IGNORE).
--
-- No user is inserted here: open the site and the first account you create (Sign in › Set up the site)
-- becomes the active Admin. After that, members sign up and wait for approval.

SET NAMES utf8mb4;

-- ---------- Roles and permissions: the rows ----------

INSERT INTO permissions (perm_key, group_name, label, scopes, sort_order) VALUES
${perms.join(',\n')}
ON DUPLICATE KEY UPDATE group_name = VALUES(group_name), label = VALUES(label), scopes = VALUES(scopes), sort_order = VALUES(sort_order);

-- Rows no longer in the app.
DELETE FROM permissions WHERE perm_key NOT IN (${rows.map((r) => q(r.key)).join(', ')});

-- ---------- Roles and permissions: default ticks (Admin always has everything) ----------

INSERT IGNORE INTO role_permissions (role, perm_key, allowed, scope) VALUES
${cells.join(',\n')};

-- ---------- Event categories ----------

INSERT IGNORE INTO event_categories (id, name, color, sort_order) VALUES
  ('cat-tournament', 'Tournament', '{"token":"primary","alpha":100}', 1),
  ('cat-training', 'Training', '{"token":"secondary","alpha":100}', 2),
  ('cat-social', 'Social', '{"token":"success","alpha":100}', 3),
  ('cat-meeting', 'Meeting', '{"token":"warning","alpha":100}', 4);

-- ---------- Site settings ----------

INSERT IGNORE INTO settings (setting_key, value) VALUES
  ('applied', ${q(JSON.stringify(appliedSets))}),
  ('event_book', '{"id":"events-default","name":"Events"}');
-- page_config is written the first time an admin saves Page Config (until then the app's starter content applies).
-- calendar_view is written the first time an admin saves the calendar's view settings (until then the app's defaults apply).

-- Palettes, typography, backgrounds, logos and menus start as the app's built-in sets:
-- the app adds any built-in missing from design_items, and saves it here the first time an admin saves it.
`

writeFileSync(new URL('database/seed.sql', root), sql)
console.log(`database/seed.sql: ${rows.length} permissions, ${cells.length} role cells`)
